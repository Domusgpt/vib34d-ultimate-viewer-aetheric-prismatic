#!/usr/bin/env node

const fs = require('fs/promises');
const path = require('path');
const vm = require('vm');
const { loadGeometrySections } = require('./utils/loadGeometrySections.js');

async function loadIconMetadata(metadataPath) {
    const raw = await fs.readFile(metadataPath, 'utf8');
    return JSON.parse(raw);
}

function isEffectivelyInteger(value) {
    return Number.isInteger(value) || Math.abs(value - Math.round(value)) < 1e-6;
}

function formatNumber(value) {
    if (isEffectivelyInteger(value)) {
        return String(Math.round(value));
    }

    const abs = Math.abs(value);

    if (abs >= 100) {
        return value.toFixed(0);
    }

    if (abs >= 10) {
        return value.toFixed(1);
    }

    return value.toFixed(2);
}

function formatRange(min, max) {
    if (min === undefined || max === undefined) {
        return '—';
    }

    if (Math.abs(min - max) < 1e-6) {
        return formatNumber(min);
    }

    return `${formatNumber(min)} – ${formatNumber(max)}`;
}

const PARAM_LABELS = {
    gridDensity: 'Grid density',
    morphFactor: 'Morph factor',
    chaos: 'Chaos',
    speed: 'Speed',
    hue: 'Hue',
    rot4dXW: 'XW rotation',
    rot4dYW: 'YW rotation',
    rot4dZW: 'ZW rotation',
    dimension: 'Dimension'
};

async function loadGeometryLibrary(projectRoot) {
    const modulePath = path.join(projectRoot, 'src/geometry/GeometryLibrary.js');
    const source = await fs.readFile(modulePath, 'utf8');

    const transformed = `${source.replace(/export\s+class\s+GeometryLibrary/, 'class GeometryLibrary')}\nmodule.exports = { GeometryLibrary };\n`;

    const context = { module: { exports: {} }, exports: {} };
    vm.createContext(context);

    try {
        const script = new vm.Script(transformed, { filename: 'GeometryLibrary.js' });
        script.runInContext(context);
    } catch (error) {
        throw new Error(`Unable to evaluate GeometryLibrary.js: ${error.message}`);
    }

    if (!context.module.exports || !context.module.exports.GeometryLibrary) {
        throw new Error('GeometryLibrary evaluation did not yield the expected export.');
    }

    return context.module.exports.GeometryLibrary;
}

async function main() {
    const projectRoot = path.resolve('.');
    const metadataPath = path.join(projectRoot, 'docs/geometry-icons/metadata.json');
    const reportPath = path.join(projectRoot, 'DOCS/GEOMETRY-PRESET-COMPENDIUM.md');

    const [sections, metadata, GeometryLibrary] = await Promise.all([
        loadGeometrySections(),
        loadIconMetadata(metadataPath),
        loadGeometryLibrary(projectRoot)
    ]);

    if (!Array.isArray(sections) || sections.length === 0) {
        throw new Error('No geometry sections discovered while building the compendium.');
    }

    if (!Array.isArray(metadata) || metadata.length === 0) {
        throw new Error('Icon metadata is missing or empty. Run `npm run geometry:icons` first.');
    }

    const metadataByGeometry = new Map(metadata.map((entry) => [entry.geometry, entry]));
    const lines = [];

    const totalPresetCount = sections.reduce((sum, section) => sum + (section.levels || 0), 0);

    lines.push('# Geometry Preset Compendium');
    lines.push('');
    lines.push('> This file is generated by `npm run geometry:report`. Do not edit manually.');
    lines.push('');
    lines.push(`Report generated on ${new Date().toISOString()}.`);
    lines.push('');
    lines.push('## Summary');
    lines.push('');
    lines.push('| Metric | Value |');
    lines.push('| --- | ---: |');
    lines.push(`| Geometry families | ${sections.length} |`);
    lines.push(`| Total preset slots | ${totalPresetCount} |`);
    lines.push(`| Icon manifest entries | ${metadata.length} |`);
    lines.push('');

    lines.push('## Geometry Overview');
    lines.push('');
    lines.push('| Index | Geometry | Preset slots | Icon |');
    lines.push('| ---: | --- | ---: | --- |');

    for (const section of sections) {
        const iconEntry = metadataByGeometry.get(section.geometry);
        const iconPath = iconEntry ? `../docs/geometry-icons/${iconEntry.file}` : null;
        const iconMarkdown = iconPath ? `![${section.name} icon](${iconPath})` : '—';
        lines.push(`| ${section.geometry} | ${section.name} | ${section.levels} | ${iconMarkdown} |`);
    }

    lines.push('');

    let variationOffset = 0;

    for (const section of sections) {
        const iconEntry = metadataByGeometry.get(section.geometry);
        const iconPath = iconEntry ? `../docs/geometry-icons/${iconEntry.file}` : null;

        lines.push(`## ${section.geometry} — ${section.name}`);
        lines.push('');

        if (iconPath) {
            lines.push(`![${section.name} icon](${iconPath})`);
            lines.push('');
        }

        const variationLabels = Array.from({ length: section.levels }, (_, level) => {
            const geometryName = GeometryLibrary.getGeometryName(section.geometry);
            return `${geometryName} LATTICE ${level + 1}`;
        });

        const variationParams = Array.from({ length: section.levels }, (_, level) =>
            GeometryLibrary.getVariationParameters(section.geometry, level)
        );

        const paramKeys = Object.keys(variationParams[0] || {});

        const envelopes = paramKeys.map((key) => {
            const values = variationParams.map((params) => params[key]);
            const min = Math.min(...values);
            const max = Math.max(...values);
            return { key, min, max };
        });

        const rangeStart = variationOffset + 1;
        const rangeEnd = variationOffset + section.levels;
        variationOffset += section.levels;

        lines.push(`- **Preset slots:** ${section.levels}`);
        lines.push(`- **Global preset indices:** ${rangeStart === rangeEnd ? rangeStart : `${rangeStart}–${rangeEnd}`}`);

        if (iconEntry) {
            lines.push(`- **Icon file:** [${iconEntry.file}](${iconPath})`);
            lines.push(`- **Icon segments:** ${iconEntry.segments}`);
        } else {
            lines.push('- **Icon file:** _missing_');
        }

        lines.push('- **Preset labels:**');
        variationLabels.forEach((label, index) => {
            const ordinal = String(index + 1).padStart(2, '0');
            lines.push(`  - ${ordinal} · ${label}`);
        });

        if (envelopes.length) {
            lines.push('- **Parameter envelopes:**');
            envelopes.forEach(({ key, min, max }) => {
                const label = PARAM_LABELS[key] || key;
                lines.push(`  - ${label}: ${formatRange(min, max)}`);
            });
        }

        lines.push('');
    }

    await fs.writeFile(reportPath, `${lines.join('\n')}\n`, 'utf8');
    console.log(`Geometry preset compendium written to ${path.relative(projectRoot, reportPath)}`);
}

main().catch((error) => {
    console.error('Failed to build the geometry preset compendium.');
    console.error(error);
    process.exitCode = 1;
});
